#!/usr/bin/env python3
"""Regenerate launcher_html_data.h from launcher_ui_src.html.

Usage: python3 regen_launcher_html.py
Edit launcher_ui_src.html (the decoded, editable copy of the embedded UI),
then run this to rebuild the C byte-array header used by browser_server.h.
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "launcher_ui_src.html")
dst = os.path.join(here, "launcher_html_data.h")

data = open(src, "rb").read()
lines = []
for i in range(0, len(data), 16):
    chunk = data[i:i+16]
    lines.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
body = "\n".join(lines)

header = f"""// Auto-generated embedded HTML for FiveM-style GTAMP launcher
// Source of truth: src/browser/launcher_ui_src.html (edit that, then run
// regen_launcher_html.py). Do not edit this file by hand.
#pragma once

#include <cstddef>

namespace gtamp {{

static const unsigned char g_launcherHtmlData[{len(data)}] = {{
{body}
}};

inline const char* GetEmbeddedHtmlData() {{
    return reinterpret_cast<const char*>(g_launcherHtmlData);
}}

inline size_t GetEmbeddedHtmlSize() {{
    return sizeof(g_launcherHtmlData);
}}

}} // namespace gtamp
"""
open(dst, "w").write(header)
print(f"wrote {dst}: {len(data)} bytes of UI data")
